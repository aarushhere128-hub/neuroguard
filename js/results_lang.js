function updateResultsLanguage() {
    const lang = localStorage.getItem("language") || "en";
    const t = resultTranslations[lang];

    document.title = t.pageTitle;

    document.getElementById("resultHomeBtn").textContent = t.home;
    document.getElementById("resultBadge").textContent = t.badge;
    document.getElementById("resultHeading").textContent = t.heading;
    document.getElementById("resultIntro").innerHTML = t.intro;

    document.getElementById("resultPatientInfoHeading").textContent = t.patientInfo;
    document.getElementById("resultNameLabel").textContent = t.name;
    document.getElementById("resultAgeLabel").textContent = t.age;
    document.getElementById("resultGenderLabel").textContent = t.gender;

    document.getElementById("resultAssessmentTitle").textContent = t.assessment;
    document.getElementById("resultConditionsHeading").textContent = t.conditions;
    document.getElementById("resultConditionsDisclaimer").textContent = t.disclaimer;

    document.getElementById("resultFastSummaryHeading").textContent = t.fastSummary;
    document.getElementById("resultFaceLabel").textContent = t.face;
    document.getElementById("resultArmLabel").textContent = t.arm;
    document.getElementById("resultSpeechLabel").textContent = t.speech;
    document.getElementById("resultTimeLabel").textContent = t.time;

    document.getElementById("resultOverallScoreHeading").textContent = t.overallScore;
    document.getElementById("resultFastScoreLabel").textContent = t.fastScore;
    document.getElementById("resultPersonalizedScoreLabel").textContent = t.personalizedScore;
    document.getElementById("resultScoreExplanation").textContent = t.scoreExplanation;

    document.getElementById("resultRecommendationHeading").textContent = t.recommendationHeading;
    document.getElementById("recommendation").textContent = t.recommendation;

    document.getElementById("downloadReport").textContent = t.download;
    document.getElementById("emergencyButton").textContent = t.emergency;
    document.getElementById("notifyBtn").textContent = t.notify;

    document.getElementById("resultWhyHeading").textContent = t.why;
    document.getElementById("resultBrainHeading").textContent = t.brainHeading;
    document.getElementById("resultBrainText").textContent = t.brainText;
    document.getElementById("resultGoldenHeading").textContent = t.goldenHeading;
    document.getElementById("resultGoldenText").textContent = t.goldenText;
    document.getElementById("resultDriveHeading").textContent = t.driveHeading;
    document.getElementById("resultDriveText").textContent = t.driveText;

    document.getElementById("resultRetakeBtn").textContent = t.retake;
    document.getElementById("resultReturnHomeBtn").textContent = t.returnHome;

}

document.addEventListener("DOMContentLoaded", () => {
    const languageSelect = document.getElementById("languageSelect");

    if (languageSelect) {
        languageSelect.value = localStorage.getItem("language") || "en";

        languageSelect.addEventListener("change", () => {
            localStorage.setItem("language", languageSelect.value);
            updateResultsLanguage();
        });
    }

    updateResultsLanguage();
});
